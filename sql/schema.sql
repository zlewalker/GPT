-- Apply once as a database administrator. The application never runs DDL.
CREATE SCHEMA votes_app;
REVOKE ALL ON SCHEMA votes_app FROM PUBLIC, anon, authenticated;

CREATE TABLE votes_app.teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    subject TEXT NOT NULL,
    UNIQUE (name, subject)
);
CREATE TABLE votes_app.lessons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    teacher_id BIGINT NOT NULL REFERENCES votes_app.teachers(id) ON DELETE RESTRICT,
    lesson_date TEXT NOT NULL CHECK (lesson_date ~ '^\d{4}-\d{2}-\d{2}$'),
    slot INTEGER NOT NULL CHECK (slot BETWEEN 1 AND 12),
    topic TEXT NOT NULL DEFAULT '',
    duration_hours INTEGER NOT NULL DEFAULT 4 CHECK (duration_hours = 4),
    UNIQUE (teacher_id, lesson_date, slot)
);
CREATE TABLE votes_app.students (
    voter_digest TEXT PRIMARY KEY CHECK (voter_digest ~ '^[a-f0-9]{64}$'),
    initials TEXT NOT NULL UNIQUE
);
CREATE TABLE votes_app.participation (
    lesson_id BIGINT NOT NULL REFERENCES votes_app.lessons(id) ON DELETE RESTRICT,
    voter_digest TEXT NOT NULL REFERENCES votes_app.students(voter_digest) ON DELETE RESTRICT,
    PRIMARY KEY (lesson_id, voter_digest)
);
CREATE TABLE votes_app.votes (
    id TEXT PRIMARY KEY,
    lesson_id BIGINT NOT NULL REFERENCES votes_app.lessons(id) ON DELETE RESTRICT,
    rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5)
);
CREATE TABLE votes_app.settings (key TEXT PRIMARY KEY, value TEXT NOT NULL);
INSERT INTO votes_app.settings VALUES ('schema_version', '1');
CREATE INDEX votes_lesson_idx ON votes_app.votes(lesson_id);
CREATE INDEX participation_student_idx ON votes_app.participation(voter_digest);

-- Tables stay inaccessible through the Data API, even if the schema is exposed later.
ALTER TABLE votes_app.teachers ENABLE ROW LEVEL SECURITY;
ALTER TABLE votes_app.lessons ENABLE ROW LEVEL SECURITY;
ALTER TABLE votes_app.students ENABLE ROW LEVEL SECURITY;
ALTER TABLE votes_app.participation ENABLE ROW LEVEL SECURITY;
ALTER TABLE votes_app.votes ENABLE ROW LEVEL SECURITY;
ALTER TABLE votes_app.settings ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ALL TABLES IN SCHEMA votes_app FROM PUBLIC, anon, authenticated;
REVOKE ALL ON ALL SEQUENCES IN SCHEMA votes_app FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA votes_app REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;
ALTER DEFAULT PRIVILEGES IN SCHEMA votes_app REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;

-- A login role can inherit this group; it cannot alter schema or delete data.
DO $$ BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'votes_runtime') THEN
        CREATE ROLE votes_runtime NOLOGIN;
    END IF;
END $$;
GRANT USAGE ON SCHEMA votes_app TO votes_runtime;
GRANT SELECT ON ALL TABLES IN SCHEMA votes_app TO votes_runtime;
GRANT INSERT ON votes_app.teachers, votes_app.lessons, votes_app.votes,
    votes_app.participation TO votes_runtime;
GRANT UPDATE (topic, slot) ON votes_app.lessons TO votes_runtime;
GRANT INSERT, UPDATE ON votes_app.settings TO votes_runtime;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA votes_app TO votes_runtime;
CREATE POLICY runtime_teachers ON votes_app.teachers TO votes_runtime USING (true) WITH CHECK (true);
CREATE POLICY runtime_lessons ON votes_app.lessons TO votes_runtime USING (true) WITH CHECK (true);
CREATE POLICY runtime_students ON votes_app.students FOR SELECT TO votes_runtime USING (true);
CREATE POLICY runtime_participation ON votes_app.participation TO votes_runtime USING (true) WITH CHECK (true);
CREATE POLICY runtime_votes ON votes_app.votes TO votes_runtime USING (true) WITH CHECK (true);
CREATE POLICY runtime_settings ON votes_app.settings TO votes_runtime USING (true) WITH CHECK (true);
